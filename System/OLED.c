// ===== 显示一个字符（页寻址模式）=====
void OLED_ShowChar(uint8_t page, uint8_t col, char c)
{
    uint8_t i;
    const uint8_t *ptr = &ASCII[c - ' '][0];

    OLED_WriteCmd(0xB0 + page);       // 设置页地址
    OLED_WriteCmd(0x00 + (col & 0x0F)); // 列低4位
    OLED_WriteCmd(0x10 + (col >> 4));   // 列高4位

    for (i = 0; i < 5; i++)
    {
        OLED_WriteData(ptr[i]);
    }
    OLED_WriteData(0x00); // 间隔一列空白
}

// ===== 显示字符串 =====
void OLED_ShowString(uint8_t page, uint8_t col, const char *str)
{
    while (*str)
    {
        OLED_ShowChar(page, col, *str);
        col += 6;  // 每个字符占6列(5像素+1空白)
        str++;
    }
}

// ===== 开启显示（先清屏再开）=====
void OLED_DisplayOn(void)
{
    OLED_Clear();                // 先清屏
    OLED_WriteCmd(0xAF);         // 开显示
}

// ===== 关闭显示（先清屏再关）=====
void OLED_DisplayOff(void)
{
    OLED_Clear();                // 先清屏，再黑掉
    OLED_WriteCmd(0xAE);         // 关显示
}
